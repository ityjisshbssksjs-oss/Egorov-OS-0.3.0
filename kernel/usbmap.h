#ifndef EGOROV_USBMAP_H
#define EGOROV_USBMAP_H

#include "types.h"

/* ── USBMAP: сводка «тип порта -> список драйверов» ────────────────────────
 *
 * ОС определяет ТИП ПОРТА и держит для каждого типа СПИСОК драйверов,
 * из которого выбирается подходящий под подключённое устройство:
 *
 *   3.0  xHCI : мышь 3.0 | клавиатура 3.0
 *   2.0  EHCI : мышь 2.0 | клавиатура 2.0
 *   1.x  UHCI : мышь 1.x | флешка
 *   1.x  OHCI : мышь 1.x | клавиатура 1.x | флешка
 *   PS/2      : мышь PS/2 | клавиатура PS/2   (только специальные не-USB
 *                                                порты - за ними USB нет)
 *
 * Тип порта определяется по контроллеру, за которым сидит порт
 * (PCI prog-if: 0x00 UHCI / 0x10 OHCI / 0x20 EHCI / 0x30 xHCI), поэтому
 * «подключил клавиатуру - во всех портах клавиатура» больше невозможно:
 * каждый тип порта обслуживает свой список, и выбор делается по паре
 * (тип порта x устройство).
 *
 * Драйверы сообщают о сделанном выборе (usbmap_pick) после связывания
 * устройства - сводка выборов собирается здесь, в одном месте.
 */

/* Напечатать СПИСОК ДРАЙВЕРОВ по типам портов (один раз на загрузку). */
void usbmap_boot_print(void);

/* Драйвер выбрал устройство: prog_if - класс контроллера (0x00/0x10/0x20/0x30),
 * role - "mouse"/"keyboard"/"msd", port - номер порта, speed - метка типа
 * порта ("1.x"/"2.0"/"3.0").  Печатает строку выбора и запоминает её. */
void usbmap_pick(int prog_if, const char *role, int port, const char *speed);

/* Однострочная сводка выборов для СНИМКа: «мышь-2.0 порт1 (x1);
 * клавиатура-2.0 порт2 (x3)» / «выборов драйверов ещё не было». */
void usbmap_summary(char *out, int outsz);

#endif
