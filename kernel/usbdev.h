#ifndef EGOROV_USBDEV_H
#define EGOROV_USBDEV_H

/* ═══════════════════════════════════════════════════════════════════════════
 * usbdev.h — ДИСПЕТЧЕР УСТРОЙСТВ USB: шесть драйверов + реестр + опрос
 * ВСЕХ портов КАЖДУЮ СЕКУНДУ.  Egorov OS 0.3.0 (название и версия
 * заморожены: Egorov OS / 0.3.0).
 *
 * Модель (по требованию пользователя):
 *   1) ОС спрашивает у ПОРТА «кто ты?» — порт отвечает своей версией:
 *      USB 3.0 (xHCI), USB 2.0 (EHCI или порт компаньона при живом EHCI),
 *      USB 1.x (UHCI/OHCI без EHCI на машине).
 *   2) Всего ШЕСТЬ драйверов: клавиатура 1.x / 2.0 / 3.0 и мышь
 *      1.x / 2.0 / 3.0.  Драйверы подбираются ТОЛЬКО по версии порта.
 *   3) Новое устройство: сначала пробуем «драйвер клавиатуры <версия>»;
 *      если ПОДОШЁЛ — записываем в реестр и БОЛЬШЕ не подбираем этот
 *      драйвер ни к кому.  Если клавиатура уже есть (или не подошло) —
 *      пробуем «драйвер мыши <версия>».  Не подошёл и он — устройство
 *      объявляется НЕИЗВЕСТНЫМ.
 *   4) Каждую секунду, НЕЗАВИСИМО от обстоятельств, опрашиваются ВСЕ
 *      порты ВСЕХ контроллеров (UHCI/OHCI/EHCI/xHCI, каждый инстанс):
 *      переподключение, выдёргивание и новая мышь ловятся опросом.
 *
 * Физический опрос портов остаётся в драйверах контроллеров (они знают
 * свои регистры); usbdev решает, КАКОЙ драйвер отдать устройству, ведёт
 * реестр занятости и тикает раз в секунду (RTC), вызывая hotplug-обходы
 * всех шин. ══════════════════════════════════════════════════════════ */

#define USBDEV_ROLE_NONE  0
#define USBDEV_ROLE_KBD   1
#define USBDEV_ROLE_MOUSE 2

/* Печать списка шести драйверов при загрузке (после usbmap_boot_print). */
void usbdev_boot_print(void);

/* Вызывается каждый кадр (ps2_poll).  Внутри — по секундам RTC: раз в
 * секунду обходит ВСЕ порты ВСЕХ контроллеров через hotplug-функции
 * драйверов.  Дёшево и никогда не блокирует надолго.
 * Глубокий аудит #205: между секундами — лёгкий обход ~4 Гц (только
 * CHANGE/edge-фильтры xHCI/OHCI/UHCI) для быстрой реакции на hotplug;
 * интервал приблизительный, калибруется по числу вызовов за секунду. */
void usbdev_tick(void);

/* Порт с новым устройством «спрашивается»: usbdev_ask_port печатает
 * вопрос и ответ (версию порта).  ver: 1/2/3. */
void usbdev_ask_port(const char *bus, int ver, int port);

/* Попытка подобрать драйвер для НОВОГО устройства (ядро модели).
 *   ver      — версия порта (1/2/3);
 *   kbd_ok   — устройство способно быть клавиатурой (из дескрипторов);
 *   mouse_ok — способно быть мышью;
 *   bus      — подпись шины («xHCI#1», «OHCI#2», «EHCI#1», «UHCI#1»);
 *   vid/pid  — паспорт устройства (для журнала).
 * Возвращает USBDEV_ROLE_KBD / USBDEV_ROLE_MOUSE — вызывающий доводит
 * привязку до конца; при неудаче привязки обязан вызвать
 * usbdev_release(role, ...).  USBDEV_ROLE_NONE = неизвестное устройство
 * (уже напечатано, слот не занят). */
int  usbdev_try_bind(int ver, int kbd_ok, int mouse_ok,
                     const char *bus, int port,
                     unsigned vid, unsigned pid);

/* Слот занят? (быстрая проверка для драйверов) */
int  usbdev_kbd_bound(void);
int  usbdev_mouse_bound(void);

/* Освободить слот роли (устройство выдернуто / привязка не удалась). */
void usbdev_release(int role, const char *why);

/* [#461] Версия порта по prog-if контроллера = ЧЕСТНОЕ поколение ШИНЫ
 * (как Linux «usb1/usb2/usb3»): xHCI -> 3 (уточняется xh_port_ver по
 * Supported Protocol); EHCI -> 2; UHCI/OHCI -> 1 ВСЕГДА. Способность
 * ГНЕЗДА (компаньон EHCI = «USB 2.0-гнездо») — вопрос КАРТЫ ГНЕЗД
 * [#459], а не версии драйвера: глобальный флаг «есть EHCI → все
 * UHCI/OHCI-порты 2.0» врал (Linux соответствие портов компаньонов
 * вообще не знает — маршрутизацию FS/LS делает сам чипсет). */
int  usbdev_port_version(int prog_if);

/* ehci_init сообщает, найдены ли EHCI-контроллеры. [#463] теперь —
 * не «версия порта», а признак «UHCI/OHCI-порты МОГУТ быть гнёздами-
 * компаньонами» для честной пометки в КАРТЕ ГНЕЗД. */
void usbdev_set_ehci_seen(int seen);
int  usbdev_companion_possible(void);

/* [#462] Живость устройств: инкремент из каждого пути разбора HID-отчёта
 * (все шины), сброс — при привязке/отключении. Карта гнёзд печатает
 * «HID-отчётов: N (ДАННЫЕ ИДУТ)» — «ЗАНЯТ» теперь доказан потоком. */
void    usbdev_note_report(int role);
uint32_t usbdev_report_count(int role);

/* Слот занят? (универсально по роли) */
int  usbdev_bound(int role);

/* Сводка реестра для экрана/журнала: «клавиатура: xHCI#1 порт 2 (3.0);
 * мышь: OHCI#2 порт 4 (2.0)». */
void usbdev_summary(char *out, int outsz);

#endif
