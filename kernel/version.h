#ifndef EGOROV_VERSION_H
#define EGOROV_VERSION_H

/* ═══ ЭТАП 9, [#473]: НОМЕРА СБОРК ═══
 *
 * Версия ОС «0.3.0» ЗАМОРОЖЕНА; релизы различаются номером СБОРКИ:
 * «Egorov OS 0.3.0 Сборка 1», «Сборка 2» и т.д.
 *
 * Номер сборки печатается в:
 *   • меню GRUB (boot/grub.cfg — заголовки пунктов меню);
 *   • серийном баннере ядра: «=== Egorov OS 0.3.0 Сборка N kernel_main ===»;
 *   • строке ДИАГНОСТИКИ USB (kernel.c, самый конец журнала);
 *   • приветственном экране и заголовке окна «О системе» (desktop.c);
 *   • заголовке ЕДИНОЙ КАРТЫ ФИЗИЧЕСКИХ ГНЕЗД (mouse_hw.c).
 *
 * ЗАЧЕМ: по номеру сборки МГНОВЕННО видно, записалась ли новая ОС на
 * флешку (Rufus/DD-режим мог записать старый образ или не перезаписать
 * раздел).  Загрузился с флешки — в меню GRUB и в баннере ядра должен
 * стоять номер ПОСЛЕДНЕГО релиза.  Виден старый номер → на флешке
 * старый образ, перезапиши заново.
 *
 * КАК УВЕЛИЧИВАТЬ НОМЕР (один релиз = один раз):
 *   1) здесь: EGOROV_OS_BUILD_N и EGOROV_OS_BUILD_S и EGOROV_OS_FULL;
 *   2) в boot/grub.cfg: заголовки пунктов меню «… Сборка N …». */

#define EGOROV_OS_VER        "0.3.0"

#define EGOROV_OS_BUILD_N    4          /* номер сборки числом        */
#define EGOROV_OS_BUILD_S    "4"        /* тот же номер строкой       */

#define EGOROV_OS_FULL       "0.3.0 Сборка 4"   /* «версия Сборка N»   */

#endif /* EGOROV_VERSION_H */
