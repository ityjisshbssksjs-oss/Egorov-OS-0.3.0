#ifndef EGOROV_USB_KBD_H
#define EGOROV_USB_KBD_H

#include "types.h"

/* ── USB-KBD: настоящая USB-клавиатура (HID boot protocol) ─────────────────
 *
 * НЕ PS/2: отчёты interrupt-IN (endpoint 1) разбираются здесь и вливаются
 * в общую очередь ps2.c (ps2_kbd_inject / ps2_kbd_mods) как сканкоды
 * набора 1 - для всей ОС (Ctrl+J, терминал, Блокнот) USB-клавиатура
 * неотличима от PS/2, а сам PS/2 остаётся для специальных не-USB портов.
 *
 * Разбор отчёта ЕДИНЫЙ для всех шин - транспорт кладёт сырой boot-отчёт
 * в usb_kbd_parse_boot() и больше ни о чём не думает:
 *   • EHCI (2.0) - транспорт в ehci.c: qTD клавиатуры переармится там,
 *     отчёты приходят через usb_kbd_parse_boot(), опрос из usb_kbd_poll();
 *   • OHCI/xHCI  - mouse_hw.c (oh_kbd_process, тот же формат отчёта);
 *   • UHCI       - перспектива (список драйверов usbmap это место уже
 *                  держит).
 *
 * PS/2-клавиатура при этом работает как раньше: обе клавиатуры вливают
 * байты в одну очередь ps2.c и ничего не знают друг о друге.
 */

/* Разобрать boot-отчёт клавиатуры [mods][rsv][k1..k6] и влить make/break
 * набора 1 в очередь ps2.c.  bus - метка шины для журнала ("EHCI", ...).
 * pkt==0 или len<0 - СБРОС: все зажатые клавиши отпускаются break-ами
 * (вызывается при отключении устройства).  Отчёт с Report-ID
 * ([ID]mods][rsv][k1..k5]) распознаётся сам: len>=8 и r[1]!=0. */
void usb_kbd_parse_boot(const uint8_t *pkt, int len, const char *bus);

/* Явная инициализация состояния разбора (нулевой prev/mods, счётчики).
 * Вызывается при старте драйвера-транспорта (ehci_init) - состояние
 * модуля не зависит от содержимого ОЗУ до старта. */
void usb_kbd_init(void);

/* Кадровый опрос USB-клавиатур всех шин (сейчас - транспорт EHCI;
 * клавиатуры OHCI/xHCI опрашиваются в mouse_hw_poll).  Вызывается из
 * ps2_poll_key() - все потребители ввода получают клавиши автоматически. */
void usb_kbd_poll(void);

/* true, если USB-клавиатура жива хотя бы на одной шине (EHCI, OHCI/xHCI). */
bool usb_kbd_present(void);

#endif
