#ifndef EGOROV_TIMER_H
#define EGOROV_TIMER_H

#include "types.h"

/* Точные микросекундные задержки без прерываний.
 *
 * Проблема (реальное железо): все прежние *_delay(us) в драйверах —
 * циклы io_wait() (outb 0x80). Реальная длительность итерации
 * зависит от чипсета и частоты CPU: на QEMU ~20 нс, на реальном ПК
 * ~1 мкс, на быстрых машинах ещё короче. USB-тайминги (TRSTRCY
 * 50 мс, recovery после SET_ADDRESS 2 мс, debounce 100 мс)
 * нарушались => «QEMU зелёный — реальное железо мёртвое».
 *
 * Решение — калибровка цикла против PIT канала 2 (порт 0x61:
 * бит 0 = GATE2, бит 5 = OUT2), как calibrate_delay() в Linux.
 * IRQ не нужны: поллинг OUT2. Вызов timer_init() один раз при
 * старте ядра (до USB-инициализации). */
void timer_init(void);

/* Калиброванная задержка. До вызова timer_init() работает как
 * консервативный фолбэк (1 итерация ≈ 1 мкс на реальном железе). */
void kdelay_us(uint32_t us);

/* Миллисекундная обёртка. */
void kdelay_ms(uint32_t ms);

#endif
