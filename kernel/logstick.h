#ifndef EGOROV_LOGSTICK_H
#define EGOROV_LOGSTICK_H

#include "types.h"

/* ═══ [LOGS] ЭТАП 11 (build 4): журнал ядра → файл EGOROV.LOG на USB ═══
 *
 * Полная цепочка пункта 2 GRUB («LOGS to USB stick»), которой раньше
 * не было: пункт назывался «LOGS to USB stick», а запись на носитель
 * была ОТКЛЮЧЕНА (расхождение устранено — теперь название честное).
 *
 * Слои (реализация kernel/logstick.c):
 *   1. ЕДИНЫЙ ИНТЕРФЕЙС БЛОЧНОГО НАКОПИТЕЛЯ — поверх трёх уже
 *      существующих транспортов BOT/SCSI: UHCI (usb.c), OHCI
 *      (mouse_hw.c, «ЭТАП 2»), xHCI (mouse_hw.c, ЭТАП 11). Интерфейс
 *      отделён от контроллеров: ёмкость/чтение/запись сектора/ошибки.
 *   1b. [build 4] ПЕРЕЧИСЛЕНИЕ ВСЕХ НАКОПИТЕЛЕЙ: до трёх (по одному на
 *      транспорт).  КАЖДЫЙ печатается (модель INQUIRY, ёмкость READ
 *      CAPACITY) и ПРОБУЕТСЯ: запись выбирается на тот накопитель, где
 *      реально найден раздел LOGS; накопитель без раздела честно
 *      пропускается — вторая флешка больше не теряется.  ПОДТВЕРЖДЕНИЕ
 *      выбора (транспорт/модель/ёмкость/границы раздела) — перед первой
 *      записью.  Ограничение (честно): два накопителя за ОДНИМ
 *      контроллером одного типа не различаются (транспорт держит один
 *      MSD) — см. README_UHCI_KBD.md.
 *   2. ГЕОМЕТРИЯ: MBR (4 первичных раздела, расширенные 0x05/0x0F/0x85
 *      честно «не поддержаны») и GPT (защитный MBR 0xEE → заголовок
 *      «EFI PART» → первые 16 записей). Проверяются ГРАНИЦЫ раздела
 *      против реальной ёмкости (READ CAPACITY) — запись за пределы
 *      НЕВОЗМОЖНА физически (центральный страж в ls_wr()).
 *   3. ВЫБОР ОБЛАСТИ: единственная разрешённая цель записи — раздел
 *      FAT32 с МЕТКОЙ ТОМА «LOGS» (файловая система, созданная
 *      ПОЛЬЗОВАТЕЛЕМ отдельно: mkstick.py для синтетики / форматирование
 *      в Windows). Активный (загрузочный, 0x80) MBR-раздел и ESP-раздел
 *      GPT исключаются. Автоформатирования/создания разделов НЕТ.
 *   4. FAT32 (ограниченная поддержка, только то, что нужно для
 *      EGOROV.LOG): поиск/создание записи 8.3 в корне, ДОПОЛНЕНИЕ
 *      файла, выделение кластеров с обновлением ОБЕИХ копий FAT и
 *      FSInfo, рост размера в записи каталога. Чужие файлы/секторы не
 *      трогаются: пишем ТОЛЬКО кластеры цепочки EGOROV.LOG, запись
 *      каталога EGOROV.LOG и секторы FAT.
 *   4b. [build 4] ЦЕЛОСТНОСТЬ МЕТАДАННЫХ: результат обновления записи
 *      каталога (ls_dir_update) ПРОВЕРЯЕТСЯ. Если данные записаны в
 *      кластеры, а размер файла в каталоге — НЕТ, успех НЕ
 *      подтверждается: печатается точное расхождение в байтах,
 *      выгрузка останавливается (писать вслепую поверх
 *      несогласованного размера нельзя), в ИТОГе — предупреждение
 *      о несоответствии (проверка тома: chkdsk).
 *   5. БУФЕРИЗАЦИЯ [build 4] — ЖУРНАЛ С ПЕРВОГО БАЙТА: ранний
 *      ЛИНЕЙНЫЙ буфер 128 КБ (cmdline logearly=N КБ) держит старт
 *      загрузки; кольцо 64 КБ (cmdline logring=N КБ) — свежий хвост
 *      (взрывы диагностики не затирают журнал между выгрузками). Выгрузка: ранний
 *      буфер → (честный маркер «потеряно N байт», если буферы
 *      переполнены) → дельта кольца (ls_tick, 1 Гц из usbdev_tick,
 *      бюджет секторов) + финальная выгрузка при выходе из textlog.
 *      ПОТЕРЯННЫЕ БАЙТЫ НАЗЫВАЮТСЯ ЧИСЛОМ (в файле и в ИТОГе); полный
 *      журнал НЕ заявляется, если потерян хоть байт.
 *   6. ОТКАЗОУСТОЙЧИВОСТЬ: тайм-ауты транспортов ограничены (см.
 *      usb.c/mouse_hw.c), выгрузка после 3 подряд ошибок транспорта
 *      отключается (честная строка в журнал/на экран); ошибка чтения
 *      FAT/каталога отличается от «нет места»; COM1 и RAM-кольцо
 *      работают ВСЕГДА — отказ носителя не влияет на работу ОС.
 *
 * Итоговые честные строки (kernel.c, ИТОГ пункта 2):
 *   «накопитель не найден» / «накопители: N; ВЫБРАН … (модель, ёмкость)»
 *   «раздел LOGS найден: LBA …» / «EGOROV.LOG создан (кластер …)» /
 *   «ИТОГ: ЗАПИСАНО N байт» / «ИТОГ: НЕ ЗАПИСАНО: <причина>» /
 *   «ИТОГ: ПОТЕРЯНО N байт … - журнал НЕ полный». */

/* Транспорт, обслуживающий накопитель (для диагностики — КАКОЙ
 * контроллер держит флешку; интерфейс ОТДЕЛЁН от реализаций:
 * logstick не знает внутренностей ни одного из них). */
#define LS_TR_NONE   0   /* накопитель не найден                       */
#define LS_TR_UHCI   1   /* usb.c:       UHCI  + BOT/SCSI             */
#define LS_TR_OHCI   2   /* mouse_hw.c:  OHCI  + BOT/SCSI             */
#define LS_TR_XHCI   3   /* mouse_hw.c:  xHCI  + BOT/SCSI (ЭТАП 11)   */

/* Лимит файла EGOROV.LOG по умолчанию (1 МБ): журнал ядра за один
 * сеанс такого не даёт; на «много загрузок» — честная строка о
 * достижении лимита (переполнение журнала не теряет данные: RAM и
 * COM1 продолжают работать).  Переопределяется cmdline logcap=N (КБ). */
#define LS_DEFAULT_CAP  (1024u * 1024u)

/* Подготовка (один раз, режим sticklog): перечислить ВСЕ накопители
 * на трёх транспортах (модель/ёмкость каждого — в журнал), выбрать
 * тот, где найден раздел LOGS (FAT32 с меткой тома), открыть/создать
 * EGOROV.LOG.  cap_bytes — лимит файла (0 = LS_DEFAULT_CAP).  Каждый
 * шаг печатает честную диагностику. */
void ls_stick_prepare(uint32_t cap_bytes);

/* Периодическая выгрузка (вызывается usbdev_tick() раз в секунду):
 * дописывает НОВЫЕ байты klog в EGOROV.LOG.  Бюджет секторов на вызов
 * ограничен (LS_TICK_BUDGET) — вызов не может надолго занять систему.
 * Неактивна вне режима sticklog / после отказа выгрузки. */
void ls_tick(void);

/* Финальная выгрузка (выход из textlog в рабочий стол): дописывает
 * остаток журнала без ограничения бюджета секторов, печатает ИТОГ
 * («ЗАПИСАНО N байт» / «НЕ ЗАПИСАНО: причина»). */
void ls_flush_final(void);

/* Краткий статус одной строкой (для ИТОГа и снимков). */
const char *ls_status(void);

/* true, если sticklog-режим включил выгрузку (накопитель+раздел ОК). */
bool ls_active(void);

#endif
